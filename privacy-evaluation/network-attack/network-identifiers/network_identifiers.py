"""Network-Identifier Extraction Attacks (combined single-file implementation).

Adapted from `calculate_network_attack.py` in a private internal research
harness (not included in this repo; cleaned up, parameterized, and merged
here). See ./README.md for the
per-model attribution and background. This file merges what used to be four
separate scripts (identifier_common.py, netshare_identifiers.py,
netssm_identifiers.py, trafficllm_identifiers.py) into one, organized as:

    1. EXTRACTION   -- per-model code that reads raw output files and pulls
                        out the identifier fields we're attacking (an IP
                        address or a MAC address), for both the real
                        training data and the generated samples. Ports,
                        protocols, and 5-tuple flows are out of scope --
                        this file only attacks the identifiers themselves.
    2. COMPARISON    -- `compare_identifier_sets()`, the one function all
                        three models funnel into. It reduces both sides to a
                        *unique set of values* and set-intersects them.
    3. RATES         -- recall/precision are computed from that same
                        intersection (see `compare_identifier_sets()` docstring
                        below for the exact formulas).
    4. CLI           -- one `python network_identifiers.py <model> ...`
                        entry point per model (netshare / netssm / trafficllm),
                        each ending in the same `print_report()`.

## What this attack measures

Does the generator reproduce **specific, real network identifiers** -- IP
addresses and MAC addresses -- from its training data, rather than
synthesizing plausible-but-novel ones? This is a set-membership question,
distinct from ../../data-extraction (which weights by how *often* a value is
regenerated) and from ../../MIA (which asks whether one specific known
sample was a training member). This file is scoped to the identifiers
themselves -- ports, protocols, and 5-tuple flows are intentionally not
attacked here.

## How identifiers are EXTRACTED (per model)

- **NetShare**: IP identifiers are already explicit `srcip`/`dstip` columns
  in NetShare's own tabular CSV output. IPs may be stored as raw integers
  (NetShare's default bit-encoding) -- pass `--ip_columns_are_integers` to
  decode them back to dotted-quad strings via `convert_int_to_ip()` before
  comparing. NetShare's own preprocessing works at the flow/IP level only
  and never carries Ethernet frames through, so there is no MAC address to
  attack here.
- **NetSSM**: IP identifiers are read from already-decoded per-packet CSVs
  (`Src IP`/`Dst IP` columns) -- i.e. the output of turning NetSSM's raw
  generated byte sequences back into structured fields, not the raw `.txt`
  generation output itself. If the *real* side hasn't been through that step
  yet and is still raw `.pcap` captures, `--original_pcap_glob` extracts the
  same identifiers directly from the packets via
  `extract_identifiers_from_pcaps()` (scapy), mirroring
  `extract_packet_features_helper()` in a private internal research
  harness's `extract_feat_pcaps.py` (not included in this repo)
  -- the script that produces the `*_packets.csv` files in the first place.
  MAC addresses (`MAC Src`/`MAC Dst`) are a separate, *flow*-level field
  (NetSSM's per-packet CSVs don't carry them) -- pass
  `--original_flow_glob`/`--generated_flow_glob` to point at the matching
  `*_flows.csv` files, or rely on `--original_pcap_glob`, which pulls MAC
  straight from each packet's Ethernet layer alongside IP.
- **TrafficLLM**: IP identifiers are parsed out of the
  `{header dict} <hex payload>` generation format (e.g.
  `{'src': '1.2.3.4', 'dst': '5.6.7.8', 'proto': 6, 'sport': 1, 'dport': 2} <hex>`)
  using `ast.literal_eval` on the `{...}` prefix (`parse_header()`), which is
  robust to whichever subset of keys is present -- only the `src`/`dst` IP
  keys are used here. MAC addresses aren't in that header dict at all --
  they're the first 12 bytes of the raw Ethernet frame in the hex payload
  *after* the `}` (destination MAC, then source MAC);
  `parse_mac_addresses()` decodes them, mirroring the commented-out MAC
  block in `calculate_memorization_attack.py`'s `convert_hex_string()` in
  the same shared attack harness.

## How the extracted sets are COMPARED

Every extractor above, regardless of model, reduces its output to a plain
Python collection of identifier values. `compare_identifier_sets()` is the
single shared comparison step: it converts both the real (`original`) and
synthetic (`generated`) collections to `set(...)` -- so duplicates collapse
and only *unique* values matter -- and takes their intersection:

    overlap = set(original_values) & set(generated_values)

## How the RATES are calculated

From that same `overlap`, `num_original_unique`, and `num_generated_unique`:

  - **recall**    = |overlap| / |original unique values|  -- of everything in
                     the training set, how much did the attacker ever see
                     reproduced in generated output?
  - **precision** = |overlap| / |generated unique values| -- of everything
                     the generator ever produced, how much was a real
                     training value rather than a novel one?

Both are 0.0 if their denominator set is empty. This is a *simpler,
unweighted* notion of precision than in ../../data-extraction (which counts
every occurrence, not just unique values) -- both are valid, they just answer
slightly different questions ("was this value ever reproduced" vs. "how
often is output real training data").
"""

import argparse
import ast
import glob
import json
from typing import Dict, Iterable

import pandas as pd

# =============================================================================
# 1. EXTRACTION HELPERS -- shared across models
# =============================================================================


def convert_int_to_ip(num: int) -> str:
    """Integer-encoded IPv4 address (as used by NetShare's `srcip`/`dstip`
    columns) -> dotted-quad string. Part of NetShare identifier extraction."""
    return ".".join(str((int(num) >> (i * 8)) & 0xFF) for i in range(4)[::-1])


def load_concat_csv(csv_glob: str, **read_csv_kwargs) -> pd.DataFrame:
    """Read every CSV matching `csv_glob` and concatenate into one dataframe,
    skipping unreadable files. Shared extraction step for NetShare and
    NetSSM, whose identifiers live in tabular columns."""
    frames = []
    for fn in glob.glob(csv_glob):
        try:
            frames.append(pd.read_csv(fn, **read_csv_kwargs))
        except Exception as e:
            print(f"[skip] {fn}: {e}")
    if not frames:
        raise FileNotFoundError(f"No readable CSVs matched: {csv_glob}")
    return pd.concat(frames, ignore_index=True)


def extract_identifiers_from_pcaps(pcap_glob: str) -> pd.DataFrame:
    """Extract identifier fields (`Src IP`/`Dst IP`/`MAC Src`/`MAC Dst`)
    directly from raw `.pcap` files with scapy, for when the "real" side of
    an attack hasn't been decoded into a per-packet/flow CSV yet.

    This is the raw-packet-level identifier extraction step: every packet
    with both an IP layer and a TCP or UDP layer contributes one row -- the
    same packet filter used by `extract_packet_features_helper()` and
    `extract_flow_features_helper()` in a private internal research
    harness's `extract_feat_pcaps.py` (not included in this repo),
    which produce the `*_packets.csv`/`*_flows.csv` files this function is a
    drop-in alternative to. Only the IP and MAC columns are kept -- ports,
    protocol, and everything else in either source function's full feature
    set aren't needed for a set-membership identifier attack. MAC comes off
    the packet's Ethernet layer (`pkt[Ether].src`/`.dst`, `"N/A"` if no
    Ethernet layer is present -- e.g. a Linux "cooked capture"). Column
    names/values match `run_netssm()`'s CSV path(s) exactly (`Src IP`/
    `Dst IP` from `*_packets.csv`, `MAC Src`/`MAC Dst` from `*_flows.csv`),
    so this is interchangeable with either as NetSSM's `--original` source.
    """
    from scapy.all import IP, TCP, UDP, Ether, rdpcap

    rows = []
    for fn in glob.glob(pcap_glob):
        try:
            packets = rdpcap(fn)
        except Exception as e:
            print(f"[skip] {fn}: {e}")
            continue
        for pkt in packets:
            if IP in pkt and (TCP in pkt or UDP in pkt):
                rows.append(
                    {
                        "Src IP": pkt[IP].src,
                        "Dst IP": pkt[IP].dst,
                        "MAC Src": pkt[Ether].src if Ether in pkt else "N/A",
                        "MAC Dst": pkt[Ether].dst if Ether in pkt else "N/A",
                    }
                )
    if not rows:
        raise FileNotFoundError(f"No IP/TCP/UDP packets extracted from: {pcap_glob}")
    return pd.DataFrame(rows)


# =============================================================================
# 2. COMPARISON + 3. RATE CALCULATION -- the shared scoring step every model
#    funnels into after extraction
# =============================================================================


def compare_identifier_sets(original_values: Iterable, generated_values: Iterable) -> Dict[str, float]:
    """Compare two collections of extracted identifier values (IPs or MACs)
    and compute recall/precision over their *unique* value sets.

    COMPARISON: both inputs are reduced to sets, so repeats collapse and only
    distinct values matter; `overlap` is their intersection.

    RATES:
      recall    = |overlap| / |original_unique|   (0.0 if original_unique is empty)
      precision = |overlap| / |generated_unique|  (0.0 if generated_unique is empty)
    """
    original_unique = set(original_values)
    generated_unique = set(generated_values)
    overlap = original_unique & generated_unique

    recall = len(overlap) / len(original_unique) if original_unique else 0.0
    precision = len(overlap) / len(generated_unique) if generated_unique else 0.0

    return {
        "num_original_unique": len(original_unique),
        "num_generated_unique": len(generated_unique),
        "num_overlap_unique": len(overlap),
        "recall": recall,
        "precision": precision,
    }


def print_report(title: str, metrics: Dict[str, float]) -> None:
    print(f"--- Network-identifier extraction report: {title} ---")
    print(f"  Original unique values:  {metrics['num_original_unique']}")
    print(f"  Generated unique values: {metrics['num_generated_unique']}")
    print(f"  Overlap (unique):        {metrics['num_overlap_unique']}")
    print(f"  Recall (training values ever reproduced):    {metrics['recall']:.4f}")
    print(f"  Precision (generated output that is real):  {metrics['precision']:.4f}")


# =============================================================================
# NetShare
# =============================================================================
# EXTRACTION: NetShare's CSV output already has explicit srcip/dstip
# columns (unlike NetDiffusion, which drops IPs before training). IPs may
# be stored as integers (NetShare's default bit-encoding);
# `--ip_columns_are_integers` routes them through convert_int_to_ip() first.
# No MAC: NetShare's preprocessing never carries an Ethernet frame.
# COMPARISON + RATES: delegated to compare_identifier_sets() / print_report()
# above, once per field.


def run_netshare(args: argparse.Namespace) -> None:
    df_original = load_concat_csv(args.original_glob, encoding="utf-8", encoding_errors="ignore")
    df_generated = load_concat_csv(args.generated_glob, encoding="utf-8", encoding_errors="ignore")

    def ip_series(df, col):
        vals = df[col]
        return set(convert_int_to_ip(v) for v in vals) if args.ip_columns_are_integers else set(vals)

    for field in ["srcip", "dstip"]:
        metrics = compare_identifier_sets(ip_series(df_original, field), ip_series(df_generated, field))
        print_report(f"NetShare / {field}", metrics)


# =============================================================================
# NetSSM
# =============================================================================
# EXTRACTION: reads already-decoded per-flow packet CSVs (Src IP/Dst IP
# columns) -- i.e. the output of decoding NetSSM's raw generated byte
# sequences back into structured fields, not the raw `.txt` generation
# output itself (see ../../MIA/netssm_blackbox_mia.py for reading the raw
# byte sequences). If the real/original side is still raw .pcap captures
# rather than those CSVs, --original_pcap_glob pulls the same identifiers
# straight out of the packets via extract_identifiers_from_pcaps().
# MAC addresses (MAC Src/MAC Dst) live only in the *_flows.csv files, not
# the *_packets.csv ones -- pass --original_flow_glob/--generated_flow_glob
# to attack them too (or rely on --original_pcap_glob, which already pulls
# MAC alongside IP).
# COMPARISON + RATES: same shared functions as NetShare.


def run_netssm(args: argparse.Namespace) -> None:
    if args.original_pcap_glob:
        df_original = extract_identifiers_from_pcaps(args.original_pcap_glob)
    else:
        df_original = load_concat_csv(args.original_glob)
    df_generated = load_concat_csv(args.generated_glob)

    for field in ["Src IP", "Dst IP"]:
        metrics = compare_identifier_sets(set(df_original[field]), set(df_generated[field]))
        print_report(f"NetSSM / {field}", metrics)

    # MAC addresses: only present in flow-level CSVs, or already extracted
    # alongside IP when the original side came from --original_pcap_glob.
    if args.original_flow_glob:
        mac_original = load_concat_csv(args.original_flow_glob)
    elif args.original_pcap_glob:
        mac_original = df_original
    else:
        mac_original = None

    mac_generated = load_concat_csv(args.generated_flow_glob) if args.generated_flow_glob else None

    if mac_original is not None and mac_generated is not None:
        for field in ["MAC Src", "MAC Dst"]:
            metrics = compare_identifier_sets(set(mac_original[field]), set(mac_generated[field]))
            print_report(f"NetSSM / {field}", metrics)
    else:
        print(
            "[info] Skipping NetSSM MAC-address comparison: pass --original_flow_glob (or "
            "--original_pcap_glob) and --generated_flow_glob -- flow-level CSVs with MAC Src/MAC Dst "
            "columns -- to enable it."
        )


# =============================================================================
# TrafficLLM
# =============================================================================
# EXTRACTION: TrafficLLM's generation-task outputs are a Python-dict-formatted
# header followed by a hex payload, e.g.
#   {'src': '147.32.84.165', 'dst': '212.117.171.138', 'proto': 6,
#    'sport': 2167, 'dport': 65500} <hex bytes>
# (see `tutorials/generation.py`'s `build_header()` in the vendored
# TrafficLLM folder). `parse_header()` extracts and parses the `{...}` prefix
# with `ast.literal_eval` (robust to whichever subset of keys is present)
# rather than manual string-splitting; extract_field_from_*() then pulls the
# `src`/`dst` IP out of every line of the training JSONL / generated .txt
# files (the `proto`/`sport`/`dport` keys are ignored -- out of scope here).
# MAC addresses aren't in the header dict -- they're the first 12 bytes of
# the raw Ethernet frame in the hex payload that follows it (dst MAC, then
# src MAC); parse_mac_addresses() decodes them.
# COMPARISON + RATES: same shared functions as NetShare/NetSSM.


def parse_header(text: str):
    """Extract and parse the `{...}` header dict prefix of a TrafficLLM
    generation-task output/sample. Returns None if no parseable header is found."""
    if "{" not in text or "}" not in text:
        return None
    try:
        header_str = text[text.index("{"): text.index("}") + 1]
        return ast.literal_eval(header_str)
    except (ValueError, SyntaxError):
        return None


def extract_field_from_jsonl(jsonl_path: str, field: str) -> list:
    values = []
    with open(jsonl_path, "r", encoding="utf-8") as f:
        for line in f:
            if not line.strip():
                continue
            header = parse_header(json.loads(line)["output"])
            if header and field in header:
                values.append(header[field])
    return values


def extract_field_from_generated(txt_glob: str, field: str) -> list:
    values = []
    for fn in glob.glob(txt_glob):
        with open(fn, "r", encoding="utf-8") as f:
            for line in f:
                if not line.strip():
                    continue
                header = parse_header(line)
                if header and field in header:
                    values.append(header[field])
    return values


def parse_mac_addresses(text: str):
    """Extract (dst_mac, src_mac) as colon-hex strings from the raw
    Ethernet-frame hex payload that follows a TrafficLLM
    `{header dict} <hex payload>` line. The header dict has no MAC fields --
    MAC addresses instead live in the packet payload itself: the first 6
    bytes are the destination MAC and the next 6 are the source MAC
    (standard Ethernet header byte order). Returns None if the payload has
    fewer than 12 decodable bytes. Mirrors the commented-out MAC block in
    `calculate_memorization_attack.py`'s `convert_hex_string()` in the
    shared attack harness (which used `" ".join(...)`-joined decimal bytes
    instead of colon-hex -- the encoding doesn't matter for set comparison
    as long as both sides use the same one, which this script does)."""
    if "}" not in text:
        return None
    hex_payload = text.split("}", 1)[-1]
    valid_hex = set("0123456789abcdefABCDEF")
    hex_string = "".join(c for c in hex_payload if c in valid_hex)
    if len(hex_string) % 2:
        hex_string = hex_string[:-1]
    if len(hex_string) < 24:  # need at least 12 bytes for both MAC addresses
        return None
    packet_bytes = bytes.fromhex(hex_string)
    dst_mac = ":".join(f"{b:02x}" for b in packet_bytes[0:6])
    src_mac = ":".join(f"{b:02x}" for b in packet_bytes[6:12])
    return dst_mac, src_mac


def extract_mac_from_jsonl(jsonl_path: str, which: str) -> list:
    idx = 0 if which == "dst" else 1
    values = []
    with open(jsonl_path, "r", encoding="utf-8") as f:
        for line in f:
            if not line.strip():
                continue
            macs = parse_mac_addresses(json.loads(line)["output"])
            if macs:
                values.append(macs[idx])
    return values


def extract_mac_from_generated(txt_glob: str, which: str) -> list:
    idx = 0 if which == "dst" else 1
    values = []
    for fn in glob.glob(txt_glob):
        with open(fn, "r", encoding="utf-8") as f:
            for line in f:
                if not line.strip():
                    continue
                macs = parse_mac_addresses(line)
                if macs:
                    values.append(macs[idx])
    return values


def run_trafficllm(args: argparse.Namespace) -> None:
    for field in ["src", "dst"]:
        original_values = extract_field_from_jsonl(args.original_jsonl, field)
        generated_values = extract_field_from_generated(args.generated_glob, field)
        metrics = compare_identifier_sets(original_values, generated_values)
        print_report(f"TrafficLLM / {field}", metrics)

    for which, label in [("dst", "dst MAC"), ("src", "src MAC")]:
        original_values = extract_mac_from_jsonl(args.original_jsonl, which)
        generated_values = extract_mac_from_generated(args.generated_glob, which)
        metrics = compare_identifier_sets(original_values, generated_values)
        print_report(f"TrafficLLM / {label}", metrics)


# =============================================================================
# 4. CLI
# =============================================================================


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Network-identifier extraction attacks (NetShare / NetSSM / TrafficLLM) in one script. "
        "See the module docstring for how identifiers are extracted, compared, and scored."
    )
    subparsers = parser.add_subparsers(dest="model", required=True)

    p_netshare = subparsers.add_parser("netshare", help="Run the attack against NetShare's tabular CSV output.")
    p_netshare.add_argument(
        "--original_glob",
        required=True,
        help="Glob for real (pre-processed) flow CSVs, e.g. '.../<dataset>/train/*/pre_processed_data/*.csv'.",
    )
    p_netshare.add_argument(
        "--generated_glob",
        required=True,
        help="Glob for synthetic flow CSVs, e.g. '.../<dataset>/train/*/generated_data/sample_len-10/syn_dfs/chunk_id-0/epoch_id-*.csv'.",
    )
    p_netshare.add_argument(
        "--ip_columns_are_integers",
        action="store_true",
        help="Set if srcip/dstip are stored as integers (NetShare's default bit-encoding) rather than dotted-quad strings.",
    )
    p_netshare.set_defaults(func=run_netshare)

    p_netssm = subparsers.add_parser("netssm", help="Run the attack against NetSSM's decoded per-packet CSVs.")
    netssm_original = p_netssm.add_mutually_exclusive_group(required=True)
    netssm_original.add_argument(
        "--original_glob",
        help="Glob for real, already-decoded per-flow packet CSVs, e.g. "
        "'.../data_MIA_new/<dataset>/train_features/*_packets.csv'.",
    )
    netssm_original.add_argument(
        "--original_pcap_glob",
        help="Glob for real, raw .pcap captures to extract identifiers from directly (via scapy), when the "
        "decoded per-packet CSVs above don't exist yet, e.g. '.../<dataset>/train/*.pcap'. "
        "See extract_identifiers_from_pcaps().",
    )
    p_netssm.add_argument(
        "--generated_glob",
        required=True,
        help="Glob for generated per-flow packet CSVs, e.g. '.../inference/<dataset>_.../*/singleprompt_*_packets.csv'.",
    )
    p_netssm.add_argument(
        "--original_flow_glob",
        help="Optional glob for real flow-level CSVs with MAC Src/MAC Dst columns, e.g. "
        "'.../data_MIA_new/<dataset>/train_features/*_flows.csv'. Enables the MAC-address comparison "
        "(not needed if using --original_pcap_glob, which already includes MAC).",
    )
    p_netssm.add_argument(
        "--generated_flow_glob",
        help="Optional glob for generated flow-level CSVs with MAC Src/MAC Dst columns, e.g. "
        "'.../inference/<dataset>_.../*/singleprompt_*_flows.csv'. Enables the MAC-address comparison.",
    )
    p_netssm.set_defaults(func=run_netssm)

    p_trafficllm = subparsers.add_parser("trafficllm", help="Run the attack against TrafficLLM's generation-task output.")
    p_trafficllm.add_argument(
        "--original_jsonl",
        required=True,
        help="TrafficLLM-format training JSONL, e.g. "
        ".../output_TrafficLLM/<dataset>_final_train/<dataset>_final_train_preprocessed_generation_packet_train.json.",
    )
    p_trafficllm.add_argument(
        "--generated_glob",
        required=True,
        help="Glob for generated .txt files, e.g. '.../inference_new/<dataset>_<epoch>epochs/*/*_maxlen_300_temp_0_9.txt'.",
    )
    p_trafficllm.set_defaults(func=run_trafficllm)

    return parser


def main():
    args = build_parser().parse_args()
    args.func(args)


if __name__ == "__main__":
    main()
